#!/bin/sh
# Remove wardctl's own files.
#
#   sudo ./uninstall.sh                     remove the program, keep user config
#   sudo ./uninstall.sh --purge-config      also remove the invoking user's ~/.wardctl
#   ./uninstall.sh --prefix DIR             uninstall from a non-default prefix
#
# Never uninstalls tracked applications, never touches APT repositories or
# keys, never removes shared dependencies. Only files listed in wardctl's
# MANIFEST (inside PREFIX/lib/wardctl) and wardctl's cache/lock are
# removed.
#
# --purge-config removes exactly one directory: <home>/.wardctl of the
# invoking user (SUDO_UID validated against the account database; with direct
# root and no SUDO_UID, root's own home). It refuses symlinks and directories
# not owned by that user. No wildcards, no other users.
set -eu

PREFIX=/usr/local
PURGE=0
SYSTEM_CACHE=/var/cache/wardctl
SYSTEM_LOCK=/run/wardctl.lock
while [ $# -gt 0 ]; do
    case "$1" in
        --prefix) [ $# -ge 2 ] || { echo "uninstall.sh: --prefix needs a directory" >&2; exit 2; }
                  PREFIX=$2; shift 2 ;;
        --prefix=*) PREFIX=${1#--prefix=}; shift ;;
        --purge-config) PURGE=1; shift ;;
        -h|--help) sed -n '2,18p' "$0"; exit 0 ;;
        *) echo "uninstall.sh: unknown option: $1" >&2; exit 2 ;;
    esac
done
case "$PREFIX" in
    /*) ;;
    *) echo "uninstall.sh: --prefix must be an absolute path" >&2; exit 2 ;;
esac

# Test hook: lets the test suite use a fake account database and system
# paths. Ignored for root so it can never redirect a real uninstall.
if [ "${WARDCTL_TEST_MODE:-}" = 1 ] && [ "$(id -u)" -ne 0 ]; then
    SYSTEM_CACHE=${WARDCTL_TEST_SYSTEM_CACHE:-$SYSTEM_CACHE}
    SYSTEM_LOCK=${WARDCTL_TEST_SYSTEM_LOCK:-$SYSTEM_LOCK}
    getent_passwd() { awk -F: -v k="$1" '$3 == k || $1 == k' "${WARDCTL_TEST_PASSWD:?}"; }
else
    getent_passwd() { getent passwd "$1"; }
fi

LIBDIR="$PREFIX/lib/wardctl"
LAUNCHER="$PREFIX/bin/wardctl"
DOCDIR="$PREFIX/share/doc/wardctl"
MANIFEST="$LIBDIR/MANIFEST"
MARKER="# WARDCTL-LAUNCHER"

if [ "$PREFIX" = /usr/local ] && [ "$(id -u)" -ne 0 ]; then
    echo "uninstall.sh: uninstalling from /usr/local requires root: sudo $0" >&2
    exit 1
fi

removed=0
if [ -f "$MANIFEST" ] && [ ! -L "$MANIFEST" ]; then
    while IFS= read -r path; do
        case "$path" in
            "$LIBDIR"/*|"$DOCDIR"/*) ;;
            "$LAUNCHER")
                if ! grep -q "^$MARKER" "$path" 2>/dev/null; then
                    echo "uninstall.sh: $path is not wardctl's launcher; leaving it" >&2
                    continue
                fi ;;
            *) echo "uninstall.sh: ignoring unexpected manifest entry: $path" >&2; continue ;;
        esac
        case "$path" in *..*) echo "uninstall.sh: ignoring suspicious path: $path" >&2; continue ;; esac
        if [ -f "$path" ] || [ -L "$path" ]; then
            rm -f -- "$path"
            removed=$((removed + 1))
        fi
    done < "$MANIFEST"
    rm -f -- "$MANIFEST"
    # Only bytecode caches generated by install.sh and now-empty directories remain.
    if [ -d "$LIBDIR/wardctl" ]; then
        find "$LIBDIR/wardctl" -depth -type d -name __pycache__ -exec rm -rf -- {} + 2>/dev/null || true
        find "$LIBDIR/wardctl" -depth -type d -empty -delete 2>/dev/null || true
    fi
    rmdir -- "$LIBDIR" 2>/dev/null || true
    rmdir -- "$DOCDIR" 2>/dev/null || true
else
    echo "uninstall.sh: no wardctl installation found under $PREFIX (missing $MANIFEST)"
fi

# wardctl's own system cache (staged packages) and lock.
if [ -d "$SYSTEM_CACHE" ] && [ ! -L "$SYSTEM_CACHE" ]; then
    rm -rf -- "$SYSTEM_CACHE"
fi
if [ -f "$SYSTEM_LOCK" ] && [ ! -L "$SYSTEM_LOCK" ]; then
    rm -f -- "$SYSTEM_LOCK"
fi
echo "Removed $removed wardctl file(s). Tracked applications, APT repositories and keys were not touched."

if [ "$PURGE" -ne 1 ]; then
    echo "User configuration (~/.wardctl) was kept. Use --purge-config to remove it."
    exit 0
fi

# ---- resolve the invoking user exactly like wardctl does
if [ "$(id -u)" -eq 0 ]; then
    if [ -n "${SUDO_UID:-}" ] && [ "${SUDO_UID}" != 0 ]; then
        case "$SUDO_UID" in *[!0-9]*) echo "uninstall.sh: invalid SUDO_UID" >&2; exit 1 ;; esac
        target_uid=$SUDO_UID
    elif [ -n "${SUDO_USER:-}" ] && [ -z "${SUDO_UID:-}" ]; then
        echo "uninstall.sh: SUDO_USER set without SUDO_UID; refusing to guess" >&2; exit 1
    else
        target_uid=0
    fi
else
    target_uid=$(id -u)
fi
entry=$(getent_passwd "$target_uid" | awk -F: -v u="$target_uid" '$3 == u' | head -n 1)
[ -n "$entry" ] || { echo "uninstall.sh: uid $target_uid not in the account database" >&2; exit 1; }
name=$(printf '%s\n' "$entry" | cut -d: -f1)
home=$(printf '%s\n' "$entry" | cut -d: -f6)
if [ -n "${SUDO_USER:-}" ] && [ "$target_uid" != 0 ] && [ "$SUDO_USER" != "$name" ]; then
    echo "uninstall.sh: SUDO_USER does not match SUDO_UID; refusing" >&2; exit 1
fi
case "$home" in
    /*) ;;
    *) echo "uninstall.sh: account $name has no absolute home directory" >&2; exit 1 ;;
esac
[ "$home" != / ] || { echo "uninstall.sh: refusing to operate on home '/'" >&2; exit 1; }

target="$home/.wardctl"
if [ -L "$target" ]; then
    echo "uninstall.sh: $target is a symbolic link; refusing to remove it" >&2; exit 1
fi
if [ ! -e "$target" ]; then
    echo "No configuration at $target."
    exit 0
fi
if [ ! -d "$target" ]; then
    echo "uninstall.sh: $target is not a directory; refusing" >&2; exit 1
fi
owner=$(stat -c %u -- "$target")
if [ "$owner" != "$target_uid" ]; then
    echo "uninstall.sh: $target is owned by uid $owner, not $target_uid; refusing" >&2; exit 1
fi
rm -rf -- "$target"
echo "Removed $target (configuration of $name)."
